#!/usr/bin/env node
/**
 * Netlify Build Hook for EcoPulse
 * Reads BACKEND_URL or API_URL from Netlify environment variables
 * and writes env-config.js for client-side consumption.
 */

const fs = require('fs');
const path = require('path');

const backendUrl = process.env.BACKEND_URL || 
                   process.env.API_URL || 
                   process.env.RENDER_BACKEND_URL || 
                   '';

console.log('=== EcoPulse Netlify Build Hook ===');
if (backendUrl) {
  console.log(`Injecting BACKEND_URL: ${backendUrl}`);
} else {
  console.log('Notice: No BACKEND_URL environment variable detected.');
  console.log('The dashboard will default to same-origin or query param ?api=<url>');
}

const sanitizedUrl = backendUrl.trim().replace(/\/+$/, '');

const content = `// Auto-generated by Netlify Build Hook (build-netlify.js)
// Reads BACKEND_URL environment variable configured in Netlify Dashboard
window.ECOPULSE_BACKEND_URL = ${JSON.stringify(sanitizedUrl)};
`;

const outputPath = path.join(__dirname, 'env-config.js');
try {
  fs.writeFileSync(outputPath, content, 'utf8');
  console.log(`Successfully generated ${outputPath}`);
} catch (err) {
  console.error('Failed to write env-config.js:', err);
  process.exit(1);
}
console.log('=== Netlify Build Ready ===');
