#!/usr/bin/env python3
"""
Netlify / Python Build Hook for EcoPulse
Reads BACKEND_URL from environment variables and generates env-config.js.
Defaults to the production Render backend if no env var is set.
"""

import os
import json

DEFAULT_BACKEND_URL = "https://eco-ai-anomaly.onrender.com"

custom_env_url = (os.environ.get("BACKEND_URL") or 
                  os.environ.get("API_URL") or 
                  os.environ.get("RENDER_BACKEND_URL"))

if custom_env_url:
    backend_url = custom_env_url.strip().rstrip("/")
    print(f"=== EcoPulse Build Hook ===\nInjecting custom environment BACKEND_URL: {backend_url}")
else:
    backend_url = DEFAULT_BACKEND_URL
    print(f"=== EcoPulse Build Hook ===\nUsing default production Render backend: {DEFAULT_BACKEND_URL}")

content = f"""// Auto-generated by Netlify Build Hook (build-netlify.py)
// Default production backend URL for cloud deployments
if (typeof window !== 'undefined' && 
    window.location.hostname !== 'localhost' && 
    window.location.hostname !== '127.0.0.1' && 
    window.location.hostname !== '::1') {{
  window.ECOPULSE_BACKEND_URL = {json.dumps(backend_url)};
}}
"""

with open("env-config.js", "w", encoding="utf-8") as f:
    f.write(content)

print("Successfully generated env-config.js")
print("=== Build Ready ===")

