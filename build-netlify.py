#!/usr/bin/env python3
"""
Netlify / Python Build Hook for EcoPulse
Reads BACKEND_URL from environment variables and generates env-config.js.
Can be executed via Python or Node.js.
"""

import os
import json

backend_url = (os.environ.get("BACKEND_URL") or 
               os.environ.get("API_URL") or 
               os.environ.get("RENDER_BACKEND_URL") or 
               "").strip().rstrip("/")

print("=== EcoPulse Build Hook ===")
if backend_url:
    print(f"Injecting BACKEND_URL: {backend_url}")
else:
    print("Notice: No BACKEND_URL environment variable detected. Using local/fallback config.")

content = f"""// Auto-generated by Netlify Build Hook
window.ECOPULSE_BACKEND_URL = {json.dumps(backend_url)};
"""

with open("env-config.js", "w", encoding="utf-8") as f:
    f.write(content)

print("Successfully generated env-config.js")
print("=== Build Ready ===")
